// One-off generator for docs/PAGE-LINKS.md — a full enumeration of every
// service x area x brand and service x area x battery combo URL, grouped by
// click path (service -> brand/battery -> area) for manual QA of the pSEO
// page tree. Run with: node scripts/generate-page-links.js
import fs from "node:fs";
import path from "node:path";

const DATA_DIR = path.join(process.cwd(), "data");
const OUT_FILE = path.join(process.cwd(), "docs", "PAGE-LINKS.md");

function loadJson(name) {
  return JSON.parse(fs.readFileSync(path.join(DATA_DIR, name), "utf8"));
}

const services = loadJson("services.json");
const brands = loadJson("brands.json");
const areas = loadJson("areas.json");
const batteries = loadJson("batteries.json");

const lines = [];
lines.push("# Page Links — Service x Brand x Area and Service x Battery x Area");
lines.push("");
lines.push("Auto-generated by `scripts/generate-page-links.js`. Do not hand-edit.");
lines.push("");
lines.push(`Services: ${services.length}, Brands: ${brands.length}, Areas: ${areas.length}, Batteries: ${batteries.length}`);
lines.push("");
lines.push("Click path: open the service hub -> pick a brand (or battery) -> pick an area -> land on the combo page below.");
lines.push("Every URL renders real content (gated indexable/noindex per `docs/BATTERY-PERMUTATION.md`); none 404.");
lines.push("");
lines.push("## Part 1 — Service x Brand x Area  (`/{service}/[area]/brand/[brand]`)");
lines.push("");

for (const service of services) {
  lines.push(`### Service: ${service.name} (\`${service.slug}\`)`);
  lines.push("");
  for (const brand of brands) {
    lines.push(`#### Brand: ${brand.name}`);
    for (const area of areas) {
      const url = `/${service.slug}/${area.slug}/brand/${brand.slug}`;
      lines.push(`- [${area.name}](${url})`);
    }
    lines.push("");
  }
}

lines.push("## Part 2 — Service x Battery (SKU) x Area  (`/{service}/[area]/battery/[battery]`)");
lines.push("");

for (const service of services) {
  lines.push(`### Service: ${service.name} (\`${service.slug}\`)`);
  lines.push("");
  for (const battery of batteries) {
    lines.push(`#### Battery: ${battery.name}`);
    for (const area of areas) {
      const url = `/${service.slug}/${area.slug}/battery/${battery.slug}`;
      lines.push(`- [${area.name}](${url})`);
    }
    lines.push("");
  }
}

fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
fs.writeFileSync(OUT_FILE, lines.join("\n") + "\n");

const brandLinks = services.length * brands.length * areas.length;
const batteryLinks = services.length * batteries.length * areas.length;
console.log(`Wrote ${OUT_FILE}`);
console.log(`Brand-tier links: ${brandLinks}`);
console.log(`Battery-tier links: ${batteryLinks}`);
console.log(`Total links: ${brandLinks + batteryLinks}`);
